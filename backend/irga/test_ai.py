def test_ai_analysis():
    """Тестирование ИИ-анализа"""
    ai = AIProcessor()
    
    test_messages = [
        "Купить молоко",
        "Оплатить интернет завтра",
        "Позвонить врачу на следующей неделе",
        "Прочитать книгу по Python",
        "Встретиться с другом в кафе",
        "Что у меня на сегодня?",
        "Сходил к врачу"
    ]
    
    print("🧠 Тестирование ИИ-анализа TaskFlowAI:")
    print("=" * 50)
    
    for message in test_messages:
        print(f"\n📝 Сообщение: '{message}'")
        
        try:
            result = ai.analyze_message(message, CATEGORIES)
            
            # Находим название категории
            category_name = "Неизвестно"
            if result.get('category_id'):
                for cat_id, cat_name in CATEGORIES:
                    if cat_id == result['category_id']:
                        category_name = cat_name
                        break
            
            print(f"   Тип: {result.get('type', 'неизвестно')}")
            print(f"   Категория: {category_name} (ID: {result.get('category_id')})")
            print(f"   Статус: {result.get('status', 'неизвестно')}")
            print(f"   Время: {result.get('planned_time', 'не указано')}")
            print(f"   Тип выполнения: {result.get('execution_type', 'не указано')}")
            
        except Exception as e:
            print(f"   ❌ Ошибка: {e}")
    
    print("\n🎉 Тестирование завершено!")

if __name__ == "__main__":
    test_ai_analysis()